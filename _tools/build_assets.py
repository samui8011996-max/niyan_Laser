"""Regenerate the bundled assets for the 辦公室 (office lucky-cat) engraving item.

Outputs
  default-templates.js    - every 辦公室*.svg inlined as a JS string (templates
                            the generator draws the customer's 刻印文字 into)
  default-fonts.js        - small "core" file: declares DEFAULT_FONTS and
                            FONT_COVERAGE (the AaWanWan codepoint ranges used
                            to warn about characters it cannot engrave)
  default-font-mobo.js    ─┐
  default-font-jf.js       │ one font each, base64, assigned onto
  default-font-chenyu.js   │ DEFAULT_FONTS.<KEY> so index.html can load them
  default-font-wanwan.js  ─┘ as separate <script> tags

Fonts used to live merged into one default-fonts.js, but base64-encoding all
four together produced a ~36MB file — over GitHub's 25MB drag-and-drop web
upload limit, so pushing font updates through the browser silently failed on
any machine that only has that upload path (the file just never made it into
the repo, so AaWanWan didn't render there even though it worked locally).
Splitting one file per font keeps every file comfortably under 25MB.

Run from the project root:  python _tools\\build_assets.py
"""
import base64
import glob
import json
import os
import re
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, '素材來源')   # 原始 SVG/字型等來源檔(網站執行時不會讀,只有重建 default-*.js 時用)


# ── templates ────────────────────────────────────────────────────────────────
def minify_svg(text):
    text = re.sub(r'<\?xml[^>]*\?>\s*', '', text)
    text = re.sub(r'<!--.*?-->', '', text, flags=re.S)
    text = re.sub(r'>\s+<', '><', text.strip())
    text = re.sub(r'\s*\n\s*', ' ', text)
    return re.sub(r'  +', ' ', text)


def build_templates():
    out = {}
    for path in sorted(glob.glob(os.path.join(SRC, '辦公室*.svg'))):
        name = os.path.splitext(os.path.basename(path))[0]
        with open(path, encoding='utf-8') as fh:
            out[name] = minify_svg(fh.read())
    body = ',\n'.join('  %s: %s' % (json.dumps(k, ensure_ascii=False), json.dumps(v, ensure_ascii=False))
                      for k, v in out.items())
    js = ('// Auto-generated by _tools/build_assets.py: 辦公室款雷雕樣板(來自資料夾裡的 辦公室*.svg)。\n'
          '// key = 檔名(不含 .svg),例如「辦公室一對_無圖案」;刻印文字會由 index.html 依樣板內容排進圖裡。\n'
          'const DEFAULT_TEMPLATES = {\n' + body + ',\n};\n')
    dest = os.path.join(ROOT, 'default-templates.js')
    with open(dest, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(js)
    print('default-templates.js: %d 個樣板, %.1f KB' % (len(out), os.path.getsize(dest) / 1024))
    return out


# ── font coverage (minimal TTF cmap reader) ──────────────────────────────────
def cmap_codepoints(data):
    num_tables = struct.unpack('>H', data[4:6])[0]
    tables = {}
    for i in range(num_tables):
        off = 12 + 16 * i
        tag = data[off:off + 4].decode('latin-1')
        toff, tlen = struct.unpack('>II', data[off + 8:off + 16])
        tables[tag] = (toff, tlen)
    base = tables['cmap'][0]
    n = struct.unpack('>H', data[base + 2:base + 4])[0]
    cps = set()
    for i in range(n):
        pid, eid, sub = struct.unpack('>HHI', data[base + 4 + 8 * i:base + 12 + 8 * i])
        if pid == 0 or (pid == 3 and eid in (1, 10)):
            cps |= read_subtable(data, base + sub)
    return cps


def read_subtable(data, off):
    fmt = struct.unpack('>H', data[off:off + 2])[0]
    cps = set()
    if fmt == 4:
        segx2 = struct.unpack('>H', data[off + 6:off + 8])[0]
        seg = segx2 // 2
        ends = struct.unpack('>%dH' % seg, data[off + 14:off + 14 + segx2])
        sp = off + 16 + segx2
        starts = struct.unpack('>%dH' % seg, data[sp:sp + segx2])
        dp = sp + segx2
        deltas = struct.unpack('>%dh' % seg, data[dp:dp + segx2])
        rp = dp + segx2
        ranges = struct.unpack('>%dH' % seg, data[rp:rp + segx2])
        for i in range(seg):
            if starts[i] == 0xFFFF:
                continue
            for cp in range(starts[i], ends[i] + 1):
                if ranges[i] == 0:
                    g = (cp + deltas[i]) & 0xFFFF
                else:
                    gi = rp + 2 * i + ranges[i] + 2 * (cp - starts[i])
                    if gi + 2 > len(data):
                        continue
                    g = struct.unpack('>H', data[gi:gi + 2])[0]
                    if g:
                        g = (g + deltas[i]) & 0xFFFF
                if g:
                    cps.add(cp)
    elif fmt == 12:
        ngroups = struct.unpack('>I', data[off + 12:off + 16])[0]
        for i in range(ngroups):
            s, e, g = struct.unpack('>III', data[off + 16 + 12 * i:off + 28 + 12 * i])
            if g:
                cps.update(range(s, e + 1))
    elif fmt == 6:
        first, count = struct.unpack('>HH', data[off + 6:off + 10])
        for i in range(count):
            if struct.unpack('>H', data[off + 10 + 2 * i:off + 12 + 2 * i])[0]:
                cps.add(first + i)
    elif fmt == 0:
        for cp in range(256):
            if data[off + 6 + cp]:
                cps.add(cp)
    return cps


def to_ranges(cps):
    out = []
    for cp in sorted(cps):
        if out and cp == out[-1][1] + 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


# key -> (font file on disk, mime format string for the data: URL)
FONT_FILES = {
    'MOBO':   ('MOBO-Bold.otf', 'font/otf'),
    'JF':     ('jf-openhuninn-2.0.ttf', 'font/ttf'),
    'CHENYU': ('ChenYuluoyan-2.0-Thin.ttf', 'font/ttf'),
    'WANWAN': ('AaWanWan.ttf', 'font/ttf'),
}


def build_fonts():
    core = ('// Auto-generated by _tools/build_assets.py: 內建字體的協調檔。\n'
            '// 每個字體的 base64 資料各自放在 default-font-<key>.js(逐一 <script> 載入,\n'
            '// 掛到這裡宣告的 DEFAULT_FONTS 上),不合併成一個檔案,\n'
            '// 避免單一檔案超過 GitHub 網頁版拖曳上傳的 25MB 上限。\n'
            'const DEFAULT_FONTS = {};\n')

    for key, (filename, mime) in FONT_FILES.items():
        path = os.path.join(SRC, filename)
        data = open(path, 'rb').read()
        b64 = base64.b64encode(data).decode('ascii')
        dest = os.path.join(ROOT, 'default-font-%s.js' % key.lower())
        js = ('// Auto-generated by _tools/build_assets.py from %s. 掛到 default-fonts.js 宣告的 DEFAULT_FONTS 上,\n'
              '// 這個檔案本身不能單獨載入(要在它之前先載入 default-fonts.js)。\n'
              'DEFAULT_FONTS.%s = "data:%s;base64,%s";\n' % (filename, key, mime, b64))
        with open(dest, 'w', encoding='utf-8', newline='\n') as fh:
            fh.write(js)
        print('default-font-%s.js: %.1f MB' % (key.lower(), os.path.getsize(dest) / 1048576))

    # AaWanWan 缺少部分繁體字(例如「貓」「黃」「吳」),記下它 cmap 實際涵蓋的字元範圍,
    # 生成結果時用這份清單提醒缺字,避免直接雷雕出空白豆腐格。
    wanwan_data = open(os.path.join(SRC, FONT_FILES['WANWAN'][0]), 'rb').read()
    ranges = to_ranges(cmap_codepoints(wanwan_data))
    core += ('\n/* AaWanWan 支援的字元範圍(從字型 cmap 產生,[起,迄] 的 Unicode 碼位)。 */\n'
             'const FONT_COVERAGE = {\n  WANWAN: %s,\n};\n' % json.dumps(ranges, separators=(',', ':')))

    dest = os.path.join(ROOT, 'default-fonts.js')
    with open(dest, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(core)
    print('default-fonts.js(協調檔+涵蓋範圍): %.1f KB' % (os.path.getsize(dest) / 1024))


if __name__ == '__main__':
    build_templates()
    build_fonts()
